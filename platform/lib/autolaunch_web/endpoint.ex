defmodule AutolaunchWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :autolaunch

  # A connected mount reads the cookie the socket handshake carried, so the
  # transport must decode it with the same options the request plug runs with.
  @session_options {Application, :fetch_env!, [:autolaunch, :session_options]}

  # A connection's process tidies all of its memory each time it tidies any.
  # Left at the default it keeps what it used to send the page, about 1.5 MB
  # for every open tab, for as long as the tab stays open.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options], fullsweep_after: 0],
    longpoll: [connect_info: [session: @session_options]]

  plug AutolaunchWeb.Plugs.CanonicalHost

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :autolaunch,
    gzip: not code_reloading?,
    only: AutolaunchWeb.static_paths(),
    only_matching:
      for(
        path <- AutolaunchWeb.static_paths(),
        Path.extname(path) != "",
        do: Path.rootname(path) <> "-"
      ),
    raise_on_missing_only: code_reloading?,
    headers: AutolaunchWeb.static_headers()

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    # The migration ledger lives in autolaunch_app, as `mix db.setup` records it.
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :autolaunch, prefix: "autolaunch_app"
  end

  # Before the request is counted, so an address refused outright writes no
  # visit line for each of its tries.
  plug :refuse_blocked

  plug Plug.RequestId
  # Which visit, and which kind of caller, each line of this request belongs to.
  plug AutolaunchWeb.VisitLog
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Every page, Markdown document, refusal and API answer, including those given
  # before the router, lets browser agents use the tools this site's pages register and carries the
  # origin-trial token, so Chrome knows it before reading `tools`.
  plug :allow_page_tools

  # One budget per client address, shared by the health check, the browser's visit
  # reports, every /api address and the share pictures, answered or not. Every
  # answer says what is left of it; past it the answer is 429 with Retry-After.
  # The auction list has a second, smaller budget of its own, and the MCP address
  # has its own.
  plug :limit_rate

  plug AutolaunchWeb.Prelaunch

  # Before the parsers, so a body they refuse on an /api address or the MCP
  # address is answered in JSON like every other API error.
  plug RegentAgentAccess.Plug,
    documents: &AutolaunchWeb.PublicDocuments.document/1,
    guide: "/agents.md",
    json_prefixes: ["api", "mcp"]

  # After the error format is chosen, so a slash address is answered as any
  # address that names nothing.
  plug AutolaunchWeb.Plugs.NoTrailingSlash

  plug AutolaunchWeb.Plugs.Parsers,
    body_reader: {AutolaunchWeb.Plugs.BodyReader, :read_body, []},
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug AutolaunchWeb.Plugs.LaunchImage
  plug AutolaunchWeb.Plugs.RuntimeSession
  plug AutolaunchWeb.Router

  @rate_limit RegentAgentAccess.RateLimit.init(
                policy: "default",
                limit: 120,
                window: 60,
                admit: &Autolaunch.Accounts.RequestRateLimiter.admit/3,
                key: &AutolaunchWeb.ClientAddress.key/1
              )

  # An agent's own request to /mcp counts against its address as on the API.
  @mcp_rate_limit RegentAgentAccess.RateLimit.init(
                    policy: "mcp_address",
                    limit: 120,
                    window: 60,
                    admit: &Autolaunch.Accounts.RequestRateLimiter.admit/3,
                    key: &AutolaunchWeb.ClientAddress.key/1
                  )

  # Claude's connector calls /mcp from Anthropic's servers, so one address carries
  # many people's connected apps: this is a ceiling against a flood, and each
  # connected account's own budget (`AutolaunchWeb.Plugs.McpAgent`) is the
  # working limit.
  @mcp_connected_rate_limit RegentAgentAccess.RateLimit.init(
                              policy: "mcp_connected_address",
                              limit: 600,
                              window: 60,
                              admit: &Autolaunch.Accounts.RequestRateLimiter.admit/3,
                              key: &AutolaunchWeb.ClientAddress.key/1
                            )

  # The auction list is answered from a five-second keep, so reading it more
  # often than every five seconds returns the same list.
  @list_rate_limit RegentAgentAccess.RateLimit.init(
                     policy: "auction-list",
                     limit: 6,
                     window: 60,
                     admit: &Autolaunch.Accounts.RequestRateLimiter.admit/3,
                     key: &AutolaunchWeb.ClientAddress.key/1
                   )

  # Chrome's WebMCP origin trial, issued to https://autolaunch.sh and valid
  # until 29 Mar 2027. The token is public; Chrome ignores it on any other host.
  @webmcp_origin_trial "AhDW0wB3iujcltck0ZP4D5GCnsNun6Tt7ZAT1ea2/irda+5c5TmsovLb373X+GV4/lYDfRE5rRbc/20Dps1J6AAAAABNeyJvcmlnaW4iOiJodHRwczovL2F1dG9sYXVuY2guc2g6NDQzIiwiZmVhdHVyZSI6IldlYk1DUCIsImV4cGlyeSI6MTgwNjM2NDgwMH0="

  # Addresses refused outright. 43.160.222.210 read the auction list every
  # 2.3 seconds around the clock (founder decision, 9 October 2026).
  @blocked [{43, 160, 222, 210}]

  defp refuse_blocked(conn, _opts) do
    {address, _source} = AutolaunchWeb.ClientAddress.key(conn)

    if address in @blocked do
      conn
      |> put_status(:forbidden)
      |> Phoenix.Controller.json(
        RegentAgentAccess.Recovery.json("Forbidden", "This address may not use this site.")
      )
      |> halt()
    else
      conn
    end
  end

  defp allow_page_tools(conn, _opts) do
    conn
    |> put_resp_header("permissions-policy", "tools=(self)")
    |> put_resp_header("origin-trial", @webmcp_origin_trial)
  end

  defp limit_rate(%Plug.Conn{method: "GET", path_info: ["api", "v1", "auctions"]} = conn, _opts) do
    case RegentAgentAccess.RateLimit.call(conn, @rate_limit) do
      %Plug.Conn{halted: true} = limited -> limited
      counted -> RegentAgentAccess.RateLimit.call(counted, @list_rate_limit)
    end
  end

  defp limit_rate(%Plug.Conn{method: "POST", path_info: ["visit-log"]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, @rate_limit)

  defp limit_rate(%Plug.Conn{path_info: ["healthz"]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, @rate_limit)

  defp limit_rate(%Plug.Conn{path_info: ["api" | _]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, @rate_limit)

  defp limit_rate(%Plug.Conn{path_info: ["mcp" | _]} = conn, _opts) do
    case Plug.Conn.get_req_header(conn, "authorization") do
      ["Bearer " <> _token] -> RegentAgentAccess.RateLimit.call(conn, @mcp_connected_rate_limit)
      _no_token -> RegentAgentAccess.RateLimit.call(conn, @mcp_rate_limit)
    end
  end

  # A share picture is drawn on the first request for each version of it, so
  # the pictures share the API's budget.
  defp limit_rate(%Plug.Conn{path_info: [kind, _symbol, _tail, "share.png"]} = conn, _opts)
       when kind in ["auctions", "tokens"],
       do: RegentAgentAccess.RateLimit.call(conn, @rate_limit)

  defp limit_rate(conn, _opts), do: conn
end
